# Student details
name = "Gopal"
marks = [85, 90, 78, 65, 92]

# Total marks
total = sum(marks)

# Average marks
average = total / len(marks)

# Highest and lowest marks
highest = max(marks)
lowest = min(marks)

# Display result
print("Student Name:", name)
print("Total Marks:", total)
print("Average Marks:", average)
print("Highest Marks:", highest)
print("Lowest Marks:", lowest)
